import { isValidIsoTimestamp } from "@shared/timestamp";
import { describe, expect, test } from "vitest";

describe("isValidIsoTimestamp", () => {
  test.each([
    "2024-02-10T08:00:00Z",
    "2024-02-10T08:00:00.123Z",
    "2024-02-10T08:00:00.123456Z",
    "2024-02-10T08:00Z",
    "2024-02-10T08:00:00+05:30",
    "2024-02-10T08:00:00-08:00",
    "2024-02-29T12:00:00Z",
    "2024-02-10T23:59:59Z",
    "0050-01-01T00:00:00Z",
    "0000-02-29T00:00:00Z",
    "0000-01-01T00:00:00Z",
    "0000-01-01T01:00:00+01:00",
    "9999-12-31T23:59:59Z",
    "9999-12-31T23:59:59.999Z",
    "9999-12-31T22:59:59-01:00",
  ])("accepts %s", (value) => {
    expect(isValidIsoTimestamp(value)).toBe(true);
  });

  test.each([
    "",
    "garbage",
    "2024-02-10",
    "2024-02-10T08:00:00",
    "2024-02-10 08:00:00Z",
    "2024-13-01T00:00:00Z",
    "2024-02-10T25:00:00Z",
    "2024-02-10T24:00:00Z",
    "0050-02-30T00:00:00Z",
    "2024-02-30T00:00:00Z",
    "2023-02-29T00:00:00Z",
    "1707552000000",
    "0000-01-01T00:00:00+01:00",
    "9999-12-31T23:59:59-01:00",
    "2024-02-10T08:99:00Z",
    "2024-02-10T08:00:60Z",
    "2024-02-10T08:00:00+99:99",
  ])("rejects %j", (value) => {
    expect(isValidIsoTimestamp(value)).toBe(false);
  });
});
